curated_results = {}
for it in items:
    srn = it['row_num']
    oid = it['oid']
    if srn in overrides:
        ing, form, st = overrides[srn]
    else:
        ing = it['res_ing']
        form = it['res_form']
        st = it['res_st']
        # Strip trailing group endings if any
        for ge in known_group_endings:
            if ge.lower() in st.lower():
                idx = st.lower().rfind(ge.lower())
                st = st[:idx].strip()
        st = re.sub(r'^[,\-\s]+', '', st).strip()
        st = re.sub(r'[,\-\s]+$', '', st).strip()
        st = re.sub(r'\s+', ' ', st)
        # Clean trailing open parens
        if st.endswith('('):
            st = st[:-1].strip()
    
    curated_results[oid] = {
        'row_num': srn,
        'page': it['page'],
        'ing': ing,
        'form': form,
        'st': st
    }

